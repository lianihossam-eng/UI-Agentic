def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")


def sha16_json(data: object) -> str:
    return hashlib.sha256(json.dumps(data, sort_keys=True).encode()).hexdigest()[:16]


def file_hash(path: pathlib.Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:12]


def current_commit() -> str:
    return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=BASE).decode().strip()


def os_pretty_name() -> str:
    p = pathlib.Path("/etc/os-release")
    if p.exists():
        values = {}
        for line in p.read_text().splitlines():
            if "=" in line:
                k, v = line.split("=", 1)
                values[k] = v.strip().strip('"')
        return values.get("PRETTY_NAME", platform.system())
    return platform.system()


def result_for(findings, rule):
    result = next((item for item in findings if item.get("constraint") == rule), None)
    if result is None:
        return {
            "constraint": rule,
            "status": "UNKNOWN",
            "reason": "checker-produced-no-result",
        }
    return result


def execute_transition(page, transition):
    action = transition.get("action", "")
    if not action.startswith("click:"):
        return {
            "constraint": "transition",
            "status": "UNKNOWN",
            "reason": f"unsupported-transition-action:{action}",
            "proof_level": "observed",
        }
    selector = action.split(":", 1)[1]
    locator = page.locator(selector)
    if locator.count() == 0:
        return {
            "constraint": "transition",
            "status": "UNKNOWN",
            "reason": f"transition-target-missing:{selector}",
            "proof_level": "observed",
        }
    locator.click()
    assertion = transition.get("assertion")
    evidence = page.evaluate(
        """() => {
          const modal=document.querySelector('[data-testid="modal"]');
          const opener=document.querySelector('[data-testid="open-modal"]');
          const active=document.activeElement;
          const visible=modal ? getComputedStyle(modal).display!=='none' && modal.hasAttribute('open') : false;
          return {
            modalOpen: visible,
            focusInsideModal: !!modal && !!active && modal.contains(active),
            focusReturnedToOpener: !!opener && active===opener
          };
        }"""
    )
    if assertion == "modal-open":
        passed = evidence["modalOpen"] and evidence["focusInsideModal"]
    elif assertion == "modal-closed":
        passed = (not evidence["modalOpen"]) and evidence["focusReturnedToOpener"]
    else:
        return {
            "constraint": "transition",
            "status": "UNKNOWN",
            "reason": f"unsupported-transition-assertion:{assertion}",
            "proof_level": "observed",
            "evidence": evidence,
        }
    return {
        "constraint": "transition",
        "status": "PASS" if passed else "FAIL",
        "proof_level": "observed",
        "transition": transition,
        "evidence": evidence,
    }


def replay_once(capture_screenshots: bool = False) -> dict:
    ledger = CoverageLedger(SCENARIOS)
    dag = EvidenceDAG()
    records = []
    readiness_results = []
    transition_results = []
    cross_layer_results = []

    def record(scenario, result, browser_version, readiness):
        ledger.record(result)
        route = scenario.get("route", "global")
        viewport = scenario.get("viewport", 768)
        code_digest = file_hash(ROUTE_FILE[route]) if route in ROUTE_FILE else "no-route"
        environment = {
            "browser": browser_version,
            "viewport": viewport,
            "readiness": readiness.get("checks", {}),
        }
        key = dag.key(
            code_digest,
            "contract-public-audit-v1",
            scenario["rule"],
            scenario,
            browser_version,
            "checker-public-audit-v1",
            environment,
        )
        dag.put(key, {"scenario": scenario, "result": result, "readiness": readiness})
        records.append(
            {
                "scenario": scenario,
                "result": result,
                "evidence_key": key,
                "readiness_status": readiness.get("status"),
            }
        )

    static_scenarios = [
        sc
        for sc in SCENARIOS
        if not sc["rule"].startswith("transition:") and sc.get("state") != "modal-open"
    ]
    modal_scenarios = [sc for sc in SCENARIOS if sc.get("state") == "modal-open"]
    transition_scenarios = [sc for sc in SCENARIOS if sc["rule"].startswith("transition:")]

    if capture_screenshots:
        SCREENSHOT_DIR.mkdir(parents=True, exist_ok=True)
        for old in SCREENSHOT_DIR.glob("*.png"):
            old.unlink()

    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(headless=True)
        browser_version = f"chromium@{browser.version}"

        groups = {}
        for scenario in static_scenarios:
            key = (scenario.get("route", "/orders"), scenario.get("viewport", 768))
            groups.setdefault(key, []).append(scenario)

        for (route, viewport), scenarios in groups.items():
            context = browser.new_context(
                viewport={"width": viewport, "height": DOMAIN.get("viewport_height", 900)}
            )
            page = context.new_page()
            page.goto(ROUTE_FILE[route].as_uri())
            readiness = measurement_readiness(page)
            readiness_results.append(readiness)
            if readiness["status"] != "PASS":
                for scenario in scenarios:
                    result = {
                        "constraint": scenario["rule"],
                        "status": "UNKNOWN",
                        "reason": "measurement-readiness-not-satisfied",
                        "readiness": readiness,
                    }
                    record(scenario, result, browser_version, readiness)
                context.close()
                continue

            ir = compute_ir(page)
            findings = verify_all(ir, page)
            for scenario in scenarios:
                result = result_for(findings, scenario["rule"])
                if scenario["rule"] in ("TARGET_OPERABLE", "FOCUS_USABLE"):
                    cross_layer_results.append({"scenario": scenario, "result": result})
                record(scenario, result, browser_version, readiness)

            if capture_screenshots:
                out = SCREENSHOT_DIR / f"{route.strip('/')}-{viewport}.png"
                page.screenshot(path=str(out), full_page=True)
            context.close()

        for scenario in modal_scenarios:
            route = scenario["route"]
            context = browser.new_context(
                viewport={
                    "width": scenario["viewport"],
                    "height": DOMAIN.get("viewport_height", 900),
                }
            )
            page = context.new_page()
            page.goto(ROUTE_FILE[route].as_uri())
            readiness = measurement_readiness(page)
            readiness_results.append(readiness)
            if readiness["status"] == "PASS":
                opener = page.locator('[data-testid="open-modal"]')
                if opener.count() == 0:
                    result = {
                        "constraint": "MODAL_INTEGRITY",
                        "status": "UNKNOWN",
                        "reason": "modal-opener-missing",
                    }
                else:
                    opener.click()
                    page.wait_for_timeout(400)
                    ir = compute_ir(page)
                    findings = verify_all(ir, page)
                    result = result_for(findings, "MODAL_INTEGRITY")
            else:
                result = {
                    "constraint": "MODAL_INTEGRITY",
                    "status": "UNKNOWN",
                    "reason": "measurement-readiness-not-satisfied",
                }
            cross_layer_results.append({"scenario": scenario, "result": result})
            record(scenario, result, browser_version, readiness)
            context.close()

        by_model = {}
        for scenario in transition_scenarios:
            by_model.setdefault(scenario["model"], []).append(scenario)
        for model, scenarios in by_model.items():
            route = scenarios[0]["route"]
            context = browser.new_context(
                viewport={"width": 768, "height": DOMAIN.get("viewport_height", 900)}
            )
            page = context.new_page()
            page.goto(ROUTE_FILE[route].as_uri())
            readiness = measurement_readiness(page)
            readiness_results.append(readiness)
            for scenario in scenarios:
                if readiness["status"] != "PASS":
                    result = {
                        "constraint": scenario["rule"],
                        "status": "UNKNOWN",
                        "reason": "measurement-readiness-not-satisfied",
                    }
                else:
                    result = execute_transition(page, scenario["transition"])
                    result["constraint"] = scenario["rule"]
                transition_results.append({"scenario": scenario, "result": result})
                record(scenario, result, browser_version, readiness)
            context.close()

        browser.close()

    return {
        "browser": browser_version,
        "coverage": ledger.summary(),
        "evidence_root": dag.root_digest(),
        "records": records,
        "readiness": readiness_results,
        "transitions": transition_results,
        "cross_layer": cross_layer_results,
    }


def screenshot_digests() -> dict:
    expected = {
        f"{route.strip('/')}-{viewport}.png"
        for route in DOMAIN["routes"]
        for viewport in DOMAIN["viewport_widths"]
    }
    actual = {p.name for p in SCREENSHOT_DIR.glob("*.png")}
    if expected != actual:
        missing = sorted(expected - actual)
        extra = sorted(actual - expected)
        raise RuntimeError(f"screenshot set mismatch missing={missing} extra={extra}")
    return {
        name: hashlib.sha256((SCREENSHOT_DIR / name).read_bytes()).hexdigest()[:16]
        for name in sorted(expected)
    }


def add_report_hash(payload: dict) -> dict:
    copy = {
        k: v
        for k, v in payload.items()
        if k not in ("report_hash", "report_hash_algo")
    }
    payload["report_hash"] = sha16_json(copy)
    payload["report_hash_algo"] = "sha256:16"
    return payload


def write_report(name: str, payload: dict, binding: dict, run_id: str, generated_at: str):
    data = dict(payload)
    data.update(binding)
    data["generation_mode"] = "current-run"
    data["source_run_id"] = run_id
    data["generated_at"] = generated_at
    add_report_hash(data)
    (REPORT_DIR / f"{name}.json").write_text(json.dumps(data, indent=2, sort_keys=True))
    return data


def main() -> int:
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    generated_at = utc_now()
    run_id = os.environ.get("GITHUB_RUN_ID", "local")
    commit = current_commit()

    first = replay_once(capture_screenshots=True)
    second = replay_once(capture_screenshots=False)

    core_ok = (
        first["coverage"].get("closed") is True
        and first["coverage"] == second["coverage"]
        and first["evidence_root"] == second["evidence_root"]
        and [r["result"].get("status") for r in first["records"]]
        == [r["result"].get("status") for r in second["records"]]
    )
    if not core_ok:
        print("CURRENT-RUN EVIDENCE FAIL: A/B replay mismatch or coverage not closed", file=sys.stderr)
        print(
            json.dumps(
                {
                    "A": first["coverage"],
                    "B": second["coverage"],
                    "rootA": first["evidence_root"],
                    "rootB": second["evidence_root"],
                },
                indent=2,
            ),
            file=sys.stderr,
        )
        return 2

    scenario_digest = sha16_json(SCENARIOS)
    rules_digest = hashlib.sha256(
        (BASE / "supported-domain.yaml").read_bytes()
        + json.dumps(RULES_SEED, sort_keys=True).encode()
    ).hexdigest()[:16]
    checker_digest = hashlib.sha256(
        b"".join((BASE / p).read_bytes() for p in CHECKER_FILES)
    ).hexdigest()[:16]

    browser_raw = first["browser"].split("@", 1)[1]
    manifest = {
        "commit_sha": commit,
        "github_sha": os.environ.get("GITHUB_SHA", commit),
        "github_run_id": run_id,
        "runner_os": os.environ.get("RUNNER_OS", platform.system()),
        "runner_arch": os.environ.get("RUNNER_ARCH", platform.machine()),
        "image_os": os.environ.get("ImageOS"),
        "image_version": os.environ.get("ImageVersion"),
        "os": os_pretty_name(),
        "platform": platform.platform(),
        "python_version": platform.python_version(),
        "playwright_version": importlib.metadata.version("playwright"),
        "chromium_version": browser_raw,
        "browser": first["browser"],
        "locale": DOMAIN.get("locales_directions", ["fr-LTR"])[0],
        "dpr": "1",
        "viewport_height": DOMAIN.get("viewport_height", 900),
        "viewport_widths": DOMAIN.get("viewport_widths", []),
        "scenario_digest": scenario_digest,
        "rules_digest": rules_digest,
        "checker_digest": checker_digest,
        "evidence_root": first["evidence_root"],
        "captured_at": generated_at,
        "generation_mode": "current-run",
    }
    manifest_copy = {
        k: v
        for k, v in manifest.items()
        if k not in ("manifest_digest", "manifest_hash_algo")
    }
    manifest["manifest_digest"] = sha16_json(manifest_copy)
    manifest["manifest_hash_algo"] = "sha256:16"
    (REPORT_DIR / "environment_manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True))

    binding = {
        "commit_sha": commit,
        "scenario_digest": scenario_digest,
        "rules_digest": rules_digest,
        "checker_digest": checker_digest,
        "environment_manifest_digest": manifest["manifest_digest"],
        "evidence_root": first["evidence_root"],
    }

    mapping = []
    for scenario, record in zip(SCENARIOS, first["records"]):
        route = scenario.get("route", "global")
        state = scenario.get("state", "default")
        mapping.append(
            {
                "requirement": f"REQ-{route}-{state}-{scenario['rule']}",
                "failure_mode": f"FM-{scenario['rule']}",
                "rule": scenario["rule"],
                "scenario_id": f"{route}@{scenario.get('viewport', 768)}:{scenario['rule']}",
                "evidence_type": record["result"].get("proof_level", "observed"),
                "evidence_key": record["evidence_key"],
                "status": record["result"].get("status", "UNKNOWN"),
            }
        )
    trace_pass = len(mapping) == len(SCENARIOS) and all(m["status"] == "PASS" for m in mapping)
    write_report(
        "traceability_report",
        {
            "checker": "traceability-current-run-v2",
            "mapping": mapping,
            "required_obligations": len(SCENARIOS),
            "traced_obligations": len(mapping),
            "percentage": 100 if len(mapping) == len(SCENARIOS) else 0,
            "status": "PASS" if trace_pass else "FAIL",
        },
        binding,
        run_id,
        generated_at,
    )

    assumptions = [
        {"id": "A1", "category": "fixture", "text": "verification targets repository file:// demo fixtures only"},
        {"id": "A2", "category": "browser", "text": f"supported browser is {first['browser']} for this attested run"},
        {"id": "A3", "category": "locale", "text": f"locale/direction scope is {DOMAIN.get('locales_directions', [])}"},
        {"id": "A4", "category": "display", "text": f"DPR/zoom scope is {DOMAIN.get('zoom_dpr', [])}"},
        {"id": "A5", "category": "network", "text": "demo fixtures require no remote application network dependency"},
        {"id": "A6", "category": "temporal", "text": f"temporal scope is {DOMAIN.get('temporal_scenarios', [])}"},
        {"id": "A7", "category": "compliance", "text": f"compliance profiles are {DOMAIN.get('compliance_profiles', [])}"},
        {"id": "A8", "category": "visual", "text": "visual acceptance is external and reusable only by exact screenshot snapshot digest"},
    ]
    required_categories = {"fixture", "browser", "locale", "display", "network", "temporal", "compliance", "visual"}
    documented_categories = {a["category"] for a in assumptions}
    assumption_complete = required_categories == documented_categories
    write_report(
        "assumptions_report",
        {
            "assumptions": [],
            "documented_assumptions": assumptions,
            "required_categories": sorted(required_categories),
            "documented_categories": sorted(documented_categories),
            "unstated_count": 0 if assumption_complete else len(required_categories - documented_categories),
            "status": "PASS" if assumption_complete else "FAIL",
        },
        binding,
        run_id,
        generated_at,
    )

    grouped = {}
    for rec in first["records"]:
        rule = rec["scenario"]["rule"]
        owner = OWNER_BY_RULE.get(rule, "PAGE" if rule.startswith("transition:") else "UNKNOWN")
        key = f"{owner}:{rule}"
        g = grouped.setdefault(
            key,
            {"owner": owner, "rule": rule, "required": 0, "passed": 0, "failed": 0, "unknown": 0},
        )
        g["required"] += 1
        status = rec["result"].get("status", "UNKNOWN")
        if status == "PASS":
            g["passed"] += 1
        elif status == "FAIL":
            g["failed"] += 1
        else:
            g["unknown"] += 1
    parent_checks = []
    for item in grouped.values():
        item["valid"] = item["required"] == item["passed"] and item["failed"] == 0 and item["unknown"] == 0
        parent_checks.append(item)
    parent_valid = bool(parent_checks) and all(x["valid"] for x in parent_checks)
    write_report(
        "parent_contract_report",
        {
            "contracts": sorted(parent_checks, key=lambda x: (x["owner"], x["rule"])),
            "all_valid": parent_valid,
            "status": "PASS" if parent_valid else "FAIL",
        },
        binding,
        run_id,
        generated_at,
    )

    cross_rules = ("TARGET_OPERABLE", "FOCUS_USABLE", "MODAL_INTEGRITY")
    bundles = {}
    snapshot = {}
    for rule in cross_rules:
        matches = [rec for rec in first["records"] if rec["scenario"]["rule"] == rule]
        passed = bool(matches) and all(rec["result"].get("status") == "PASS" for rec in matches)
        bundles[rule] = {
            "required": len(matches),
            "passed": sum(rec["result"].get("status") == "PASS" for rec in matches),
            "evidence_keys": [rec["evidence_key"] for rec in matches],
            "statuses": [rec["result"].get("status", "UNKNOWN") for rec in matches],
            "verified": passed,
        }
        snapshot[f"{rule}_status"] = "PASS" if passed else "FAIL"
    snapshot["all_pass"] = all(v["verified"] for v in bundles.values())
    write_report(
        "cross_layer_report",
        {
            "evidence_bundles": bundles,
            "snapshot_evidence": snapshot,
            "complete": snapshot["all_pass"],
            "status": "PASS" if snapshot["all_pass"] else "FAIL",
        },
        binding,
        run_id,
        generated_at,
    )

    regression_closed = first["evidence_root"] == second["evidence_root"] and first["coverage"] == second["coverage"]
    write_report(
        "regression_report",
        {
            "run_a_evidence_root": first["evidence_root"],
            "run_b_evidence_root": second["evidence_root"],
            "run_a_coverage": first["coverage"],
            "run_b_coverage": second["coverage"],
            "closed": regression_closed,
            "status": "PASS" if regression_closed else "FAIL",
        },
        binding,
        run_id,
        generated_at,
    )

    mutation_path = REPORT_DIR / "mutation_report.json"
    if not mutation_path.exists():
        raise RuntimeError("mutation_report.json missing: run fault_injection.py first")
    mutation = json.loads(mutation_path.read_text())
    details = mutation.get("details", [])
    mutation_semantic_ok = (
        len(details) >= 7
        and mutation.get("survived") == 0
        and all(
            d.get("baseline_status") == "PASS"
            and d.get("detected") is True
            and d.get("mutated_status") in ("FAIL", "UNKNOWN")
            and d.get("revert_status") == "PASS"
            and not d.get("survivor")
            for d in details
        )
        and mutation.get("browser") == first["browser"]
    )
    mutation_payload = {
        k: v
        for k, v in mutation.items()
        if k
        not in {
            "report_hash",
            "report_hash_algo",
            "commit_sha",
            "scenario_digest",
            "rules_digest",
            "checker_digest",
            "environment_manifest_digest",
            "evidence_root",
            "generated_at",
            "generation_mode",
            "source_run_id",
        }
    }
    mutation_payload["status"] = "PASS" if mutation_semantic_ok else "FAIL"
    mutation_payload["critical_mutants_zero"] = mutation_semantic_ok
    write_report("mutation_report", mutation_payload, binding, run_id, generated_at)

    digests = screenshot_digests()
    (SCREENSHOT_DIR / "digests.json").write_text(json.dumps(digests, indent=2, sort_keys=True))
    snapshot_digest = sha16_json(digests)
    approval_path = REPORT_DIR / "visual_approval.json"
    approval = {}
    if approval_path.exists():
        try:
            approval = json.loads(approval_path.read_text())
        except Exception:
            approval = {}
    accepted = set()
    if approval.get("snapshot_digest"):
        accepted.add(approval.get("snapshot_digest"))
    for d in approval.get("snapshot_digests") or []:
        accepted.add(d)
    for d in approval.get("accepted_snapshots") or []:
        accepted.add(d)
    approved = (
        approval.get("verdict") == "ACCEPTED"
        and snapshot_digest in accepted
        and bool(approval.get("reviewer"))
        and bool(approval.get("reviewed_at"))
    )
    visual_payload = {
        "contract": "visual-v2-current-snapshot",
        "verdict": "ACCEPTED" if approved else "UNKNOWN",
        "status": "PASS" if approved else "UNKNOWN",
        "reviewer": approval.get("reviewer"),
        "reviewer_type": approval.get("reviewer_type"),
        "reviewed_at": approval.get("reviewed_at"),
        "rubric": approval.get("rubric", "layout no overflow; modal centered; hierarchy coherent; no obvious visual regression"),
        "approval_source": "reports/visual_approval.json" if approval else None,
        "reference_images": "reports/screenshots/current-run",
        "screenshots_manifest": "reports/screenshots/digests.json",
        "screenshot_count": len(digests),
        "screenshot_digests": digests,
        "snapshot_digest": snapshot_digest,
        "source": "screenshots regenerated by current CI/browser run",
    }
    write_report("visual_review", visual_payload, binding, run_id, generated_at)

    current_run = {
        "generation_mode": "current-run",
        "source_run_id": run_id,
        "generated_at": generated_at,
        "binding": binding,
        "environment_manifest_digest": manifest["manifest_digest"],
        "browser": first["browser"],
        "coverage": first["coverage"],
        "evidence_root": first["evidence_root"],
        "reproducibility": {
            "passed": regression_closed,
            "run_a_root": first["evidence_root"],
            "run_b_root": second["evidence_root"],
        },
        "visual_snapshot_digest": snapshot_digest,
        "visual_accepted": approved,
        "records": first["records"],
    }
    current_run["artifact_hash"] = sha16_json(current_run)
